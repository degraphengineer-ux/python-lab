def square(n):
    """Returns the square of a number."""
    return n * n

def is_even(n):
    """Returns True if a number is even, False otherwise."""
    return n % 2 == 0

def celsius_to_fahrenheit(c):
    """Converts Celsius to Fahrenheit using F = (C * 9/5) + 32."""
    return (c * 9/5) + 32

